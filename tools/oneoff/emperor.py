# -*- coding: utf-8 -*-
u"""Государь -> император, а где в оригинале King -- царь.

Русская синология зовёт китайского 皇帝 императором, а 王 -- царём (ваном).
"Государь" читается как русский титул, и в списке навыков "Длинный кулак
государя" выглядит чужеродно. В файлах уже был разнобой: 86 "государ*"
против 27 "император*" (Жёлтый император, Небесный император -- там иначе
и нельзя).

Заодно сверено с английским: часть "государей" на деле King -- это ваны
(Сян Юй, Гоуцзянь, чуский и уский цари, чжоуский царь Му). Они становятся
царями, как уже было в описаниях оружия.

Слова "государство", "государственный" не трогаем.
"""
import io, os, re, sys

# 1. То, что остаётся государем: monarch / ruler, не титул династии.
KEEP = [
    u'что государь в царстве',
    u'государем ста видов оружия',
]

# 2. King -> царь. Длинные раньше коротких: "чуского" перед "уского".
KINGS = [
    (u'гегемоном-государем',  u'гегемоном-царём'),
    (u'гегемон-государь',     u'гегемон-царь'),
    (u'чуского государя',     u'чуского царя'),
    (u'уского государя',      u'уского царя'),
    (u'юэский государь',      u'юэский царь'),
    (u'государя Му',          u'царя Му'),
    (u'Заманивает государя',  u'Заманивает царевича'),   # EN: prince
]

# 3. Притяжательные: род и падеж по контексту, поэтому строками.
POSS = [
    (u'Государева курица',          u'Императорская курица'),
    (u'Государев колокольчик',      u'Императорский колокольчик'),
    (u'Государев порошок',          u'Императорский порошок'),
    (u'Государевой звезды',         u'Императорской звезды'),
    (u'Государева горлянка',        u'Императорская горлянка'),
    (u'государевы одежды',          u'императорские одежды'),
    (u'государева тёмного огня',    u'императорского тёмного огня'),
    (u'государева рода',            u'императорского рода'),
    (u'Государевой',                u'Императорской'),
    (u'государеву власть',          u'императорскую власть'),
    (u'государевы кузнецы',         u'императорские кузнецы'),
    (u'государевом собрании',       u'императорском собрании'),
    (u'государевы дворцы',          u'императорские дворцы'),
]

# 4. Обычные формы. Границы слова -- по кириллице: перед "Государь" может
#    стоять литеральное \n, и обычный \b там не срабатывает.
WORDS = [
    (u'Государыня',  u'Императрица'),  (u'государыня',  u'императрица'),
    (u'Государыни',  u'Императрицы'),  (u'государыни',  u'императрицы'),
    (u'Государем',   u'Императором'),  (u'государем',   u'императором'),
    (u'Государей',   u'Императоров'),  (u'государей',   u'императоров'),
    (u'Государя',    u'Императора'),   (u'государя',    u'императора'),
    (u'Государю',    u'Императору'),   (u'государю',    u'императору'),
    (u'Государи',    u'Императоры'),   (u'государи',    u'императоры'),
    (u'Государе',    u'Императоре'),   (u'государе',    u'императоре'),
    (u'Государь',    u'Император'),    (u'государь',    u'император'),
]
CYR = u'\u0400-\u04ff'
WORD_RE = re.compile(u'(?<![%s])(?:%s)(?![%s])'
                     % (CYR, u'|'.join(w for w, _ in WORDS), CYR))
WORD_MAP = dict(WORDS)

LEFT = re.compile(u'[Гг]осудар(?!ств)')
MASK = u'\ue000%d\ue001'

ROOTS = [
    u'C:/Games/The Scroll of Taiwu/The Scroll of Taiwu_Data/StreamingAssets/Language_RU',
    u'C:/Games/The Scroll of Taiwu/Mod/TaiwuRussian/Language_RU',
    u'C:/Games/taiwu-ru-backup/Language_RU',
]


def fix(value):
    for n, keep in enumerate(KEEP):
        value = value.replace(keep, MASK % n)
    for a, b in KINGS + POSS:
        value = value.replace(a, b)
    value = WORD_RE.sub(lambda m: WORD_MAP[m.group(0)], value)
    for n, keep in enumerate(KEEP):
        value = value.replace(MASK % n, keep)
    return value


def main():
    apply = '--apply' in sys.argv
    for root in ROOTS:
        if not os.path.isdir(root):
            print('нет папки:', root)
            continue
        total = 0
        for fn in sorted(os.listdir(root)):
            path = os.path.join(root, fn)
            if not os.path.isfile(path) or not fn.endswith('.txt'):
                continue
            lines = io.open(path, encoding='utf-8').read().split(u'\n')
            hits = 0
            for i in range(1, len(lines), 2):          # только значения
                new = fix(lines[i])
                if new != lines[i]:
                    lines[i] = new
                    hits += 1
            if hits:
                total += hits
                print(u'%-42s %d' % (fn, hits))
                if apply:
                    with io.open(path, 'w', encoding='utf-8', newline='') as f:
                        f.write(u'\n'.join(lines))
            for i in range(1, len(lines), 2):
                m = LEFT.search(lines[i])
                if m and lines[i][m.start():m.start() + 30] not in u''.join(KEEP):
                    s = max(0, m.start() - 30)
                    print(u'   ОСТАЛОСЬ %s: %s' % (fn, lines[i][s:m.start() + 30]))
        print(u'%s -> %d строк\n' % (root, total))


main()
